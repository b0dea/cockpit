function evidenceRefusal(code, message) {
    return `[${code}] ${message}`
}

// A JSON.parse message quotes the bytes where parsing stopped, and evidence files may hold values
// the reader of a refusal should not see; name the file, the line and the expected shape instead.
function parseJsonText(text, path, expected, firstLine = 1) {
    try {
        return { value: JSON.parse(text) }
    } catch (error) {
        if (!(error instanceof SyntaxError)) throw error
        const line = /\(line (\d+) column \d+\)/.exec(error.message)?.[1]
        const where = line === undefined ? '' : ` at line ${Number(line) + firstLine - 1}`
        return { refusal: `${path} is not valid JSON${where}; expected ${expected}` }
    }
}

// Returns the parsed object, or the refusal text.
function parseJsonObject(text, path, firstLine = 1) {
    const { value, refusal } = parseJsonText(text, path, 'one JSON object', firstLine)
    if (refusal !== undefined) return refusal
    return value !== null && typeof value === 'object' && !Array.isArray(value) ? value : `${path} must hold one JSON object`
}

// The body of a block, and the file line its first body line sits on.
function fencedJsonBlocks(body, label) {
    return [...body.matchAll(new RegExp('```' + label + '\\s*\\n([\\s\\S]*?)\\n```', 'dg'))]
        .map(match => ({ text: match[1], firstLine: body.slice(0, match.indices[1][0]).split('\n').length }))
}

function readText(path, root, code) {
    try {
        return { text: readFileSync(resolve(root, path), 'utf8') }
    } catch (error) {
        return { errors: [evidenceRefusal(code, `${path}: ${errorCause(error)}`)] }
    }
}

function parseEvidence(path, root) {
    const read = readText(path, root, 'DOCEV001_UNREADABLE')
    if (read.errors) return read
    const blocks = fencedJsonBlocks(read.text, 'docs-evidence')
    if (blocks.length !== 1) {
        return { errors: [evidenceRefusal('DOCEV002_BLOCK_COUNT', `${path} must contain exactly one docs-evidence JSON block`)] }
    }
    const value = parseJsonObject(blocks[0].text, path, blocks[0].firstLine)
    return typeof value === 'string' ? { errors: [evidenceRefusal('DOCEV003_JSON_INVALID', value)] } : { value }
}

function resolveCandidate(root, candidate) {
    try {
        return git(root, ['rev-parse', '--verify', `${candidate}^{commit}`]).trim()
    } catch {
        // A non-zero git exit means the candidate does not resolve; the caller refuses a null.
        return null
    }
}

function commitIsAncestor(root, ancestor, candidate) {
    try {
        execFileSync('git', ['merge-base', '--is-ancestor', ancestor, candidate], { cwd: root, stdio: 'ignore' })
        return true
    } catch {
        // `merge-base --is-ancestor` exits non-zero to say "not an ancestor"; the caller refuses a false.
        return false
    }
}

function validateFixedPoint(root, expectedFixedPoint, candidate) {
    const errors = []
    if (!expectedFixedPoint) {
        return { errors: [evidenceRefusal('DOCEV010_FIXED_POINT_REQUIRED', '--expected-fixed-point is required')] }
    }
    const fixedPoint = resolveCandidate(root, expectedFixedPoint)
    const resolvedCandidate = resolveCandidate(root, candidate)
    if (fixedPoint === null) errors.push(evidenceRefusal('DOCEV011_FIXED_POINT_UNKNOWN', expectedFixedPoint))
    if (resolvedCandidate === null) errors.push(evidenceRefusal('DOCEV012_CANDIDATE_UNKNOWN', candidate))
    if (errors.length > 0) return { errors }
    if (fixedPoint === resolvedCandidate) {
        errors.push(evidenceRefusal('DOCEV013_FIXED_POINT_TOO_NEW', 'fixed point equals the candidate'))
    } else {
        try {
            execFileSync('git', ['merge-base', '--is-ancestor', fixedPoint, resolvedCandidate], { cwd: root, stdio: 'ignore' })
        } catch {
            // A non-zero exit is git's "not an ancestor" answer, and this refusal reports it.
            errors.push(evidenceRefusal('DOCEV014_FIXED_POINT_NOT_ANCESTOR', `${expectedFixedPoint} is not an ancestor of ${candidate}`))
        }
    }
    return { errors, fixedPoint, candidate: resolvedCandidate }
}

// A resolved commit's blobs never change, and one validation reads the same paths many times
// (the evidence detectors read each anchor target once per row). Every read was a git process,
// which made validation spawn-bound; the memo is keyed by repository, commit and path. A read
// that throws is not memoised, so it fails again on the next call.
const committedReads = new Map()

function committedRead(root, candidate, path, read) {
    const key = `${root}\0${candidate}\0${path}`
    if (!committedReads.has(key)) committedReads.set(key, read())
    return committedReads.get(key)
}

function sourceAt(root, candidate, path) {
    return committedRead(root, candidate, path, () => git(root, ['show', `${candidate}:${path}`]))
}

