import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import { builtinModules } from 'node:module'
import { constants } from 'node:fs'
import { lstat, open, readFile, readdir, realpath, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repositoryRoot = resolve(packageRoot, '../..')
const bundlePath = join(packageRoot, 'libexec/rulesync-generator.cjs')
const noticePath = join(packageRoot, 'libexec/rulesync-generator.NOTICE.md')
const adapterPath = join(packageRoot, 'src/surfaces/generator-adapter.ts')
const generatedHeader = '// Generated by scripts/build-rulesync-generator.mjs. Do not edit.\n'
const licenseFile = /^(?:licen[cs]e|copying|notice)(?:[.\-_]|$)/i

async function boundedRegularText(path, maxBytes = 1_048_576) {
    const status = await lstat(path)
    if (!status.isFile() || status.isSymbolicLink() || status.size > maxBytes || constants.O_NOFOLLOW === undefined) {
        throw new Error(`unsafe legal source: ${path}`)
    }
    const handle = await open(path, constants.O_RDONLY | constants.O_NOFOLLOW)
    try {
        const opened = await handle.stat()
        if (!opened.isFile() || opened.dev !== status.dev || opened.ino !== status.ino || opened.size !== status.size) {
            throw new Error(`legal source identity changed: ${path}`)
        }
        const bytes = await handle.readFile()
        const after = await handle.stat()
        if (bytes.byteLength !== opened.size || after.size !== opened.size
            || after.mtimeMs !== opened.mtimeMs || after.ctimeMs !== opened.ctimeMs) {
            throw new Error(`legal source changed while reading: ${path}`)
        }
        return new TextDecoder('utf-8', { fatal: true }).decode(bytes)
    } finally {
        await handle.close()
    }
}

async function packageForInput(input) {
    let current = dirname(resolve(repositoryRoot, input))
    while (current !== dirname(current)) {
        const manifestPath = join(current, 'package.json')
        try {
            const manifest = JSON.parse(await boundedRegularText(manifestPath, 65_536))
            if (typeof manifest.name === 'string' && typeof manifest.version === 'string') {
                return { root: await realpath(current), manifest }
            }
        } catch (error) {
            if (error?.code !== 'ENOENT') throw error
        }
        current = dirname(current)
    }
    throw new Error(`cannot establish package ownership for bundled input: ${input}`)
}

async function renderNotices(inputs) {
    const workspaceManifest = JSON.parse(await boundedRegularText(join(packageRoot, 'package.json'), 65_536))
    if (typeof workspaceManifest.version !== 'string'
        || !/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/.test(workspaceManifest.version)) {
        throw new Error('cockpit package version is unavailable for notice verification metadata')
    }
    const packages = new Map()
    for (const input of inputs) {
        if (!input.includes('node_modules/')) continue
        const item = await packageForInput(input)
        packages.set(`${item.manifest.name}@${item.manifest.version}\0${item.root}`, item)
    }
    if (![...packages.values()].some(({ manifest }) => manifest.name === 'rulesync' && manifest.version === '43.0.0')) {
        throw new Error('Rulesync 43.0.0 is absent from the bundle inventory')
    }

    const sections = []
    for (const { root, manifest } of [...packages.values()].sort((left, right) => {
        const a = `${left.manifest.name}@${left.manifest.version}`
        const b = `${right.manifest.name}@${right.manifest.version}`
        return a.localeCompare(b) || left.root.localeCompare(right.root)
    })) {
        if (typeof manifest.license !== 'string' || manifest.license.length === 0) {
            throw new Error(`license identifier unavailable for ${manifest.name}@${manifest.version}`)
        }
        const legalFiles = (await readdir(root)).filter(name => licenseFile.test(name)).sort((a, b) => a.localeCompare(b))
        if (legalFiles.length === 0) throw new Error(`license text unavailable for ${manifest.name}@${manifest.version}`)
        const texts = []
        for (const name of legalFiles) {
            const text = (await boundedRegularText(join(root, name))).replace(/\r\n?/g, '\n').trimEnd()
            if (text.length === 0) throw new Error(`empty legal text for ${manifest.name}@${manifest.version}/${name}`)
            texts.push(`### ${name}\n\n${text}`)
        }
        sections.push(`## ${manifest.name} ${manifest.version}\n\nSPDX license: ${manifest.license}\n\n${texts.join('\n\n')}`)
    }
    return `# Third-party notices for rulesync-generator.cjs\n\n<!-- cockpit:verified version=${workspaceManifest.version} -->\n\nThis file records every package whose code is included in the generated bundle.\n\n${sections.join('\n\n---\n\n')}\n`
}

export function externalRuntimeImports(source) {
    const allowed = new Set([...builtinModules, ...builtinModules.map(name => `node:${name}`)])
    const imports = new Set()
    const requireCalls = [...source.matchAll(/\brequire\s*\(/g)].length
    const literalRequires = [...source.matchAll(/\brequire\s*\((['"])([^'"]+)\1\)/g)]
    if (literalRequires.length !== requireCalls) imports.add('<dynamic require>')
    for (const match of literalRequires) {
        if (!allowed.has(match[2])) imports.add(match[2])
    }
    const importCalls = [...source.matchAll(/\bimport\s*\(/g)].length
    const literalImports = [...source.matchAll(/\bimport\s*\((['"])([^'"]+)\1\)/g)]
    if (literalImports.length !== importCalls) imports.add('<dynamic import>')
    for (const match of literalImports) {
        if (!allowed.has(match[2])) imports.add(match[2])
    }
    return [...imports].sort((a, b) => a.localeCompare(b))
}

async function renderArtifacts() {
    const result = await build({
        stdin: { contents: "export { generate } from 'rulesync'", resolveDir: repositoryRoot, sourcefile: 'cockpit-generator.js' },
        absWorkingDir: repositoryRoot,
        bundle: true,
        platform: 'node',
        format: 'cjs',
        target: 'node22',
        mainFields: ['module', 'main'],
        minify: true,
        charset: 'utf8',
        legalComments: 'none',
        metafile: true,
        write: false,
    })
    if (result.outputFiles.length !== 1) throw new Error('Rulesync bundle produced an unexpected output set')
    const bundle = `${generatedHeader}${result.outputFiles[0].text}`.replace(/^[ \t]+$/gm, '')
    const external = externalRuntimeImports(bundle)
    if (external.length > 0) throw new Error(`Rulesync bundle retained external runtime imports: ${external.join(', ')}`)
    const notice = await renderNotices(Object.keys(result.metafile.inputs))
    return { bundle, notice }
}

async function main() {
    const arguments_ = process.argv.slice(2)
    if (arguments_[0] === '--check-imports' && arguments_.length === 2) {
        const source = await boundedRegularText(resolve(arguments_[1]), 4_194_304)
        const external = externalRuntimeImports(source)
        if (external.length > 0) throw new Error(`external runtime imports: ${external.join(', ')}`)
        return
    }
    if (arguments_.length > 1 || arguments_.some(argument => argument !== '--check')) {
        throw new Error('usage: build-rulesync-generator.mjs [--check | --check-imports PATH]')
    }
    const rendered = await renderArtifacts()
    if (arguments_.length === 0) {
        await writeFile(bundlePath, rendered.bundle, { encoding: 'utf8', mode: 0o644 })
        await writeFile(noticePath, rendered.notice, { encoding: 'utf8', mode: 0o644 })
        return
    }
    const actualBundle = await readFile(bundlePath, 'utf8')
    const actualNotice = await readFile(noticePath, 'utf8')
    if (actualBundle !== rendered.bundle || actualNotice !== rendered.notice) {
        throw new Error('checked-in Rulesync bundle or legal notice is stale; run npm run bundle:rulesync --workspace @b0dea/cockpit')
    }
    const adapter = await readFile(adapterPath, 'utf8')
    const pinned = adapter.match(/const PINNED_GENERATOR_BUNDLE_SHA256 = '([a-f0-9]{64})'/)?.[1]
    const actualDigest = createHash('sha256').update(actualBundle).digest('hex')
    if (pinned !== actualDigest) throw new Error('generator adapter does not pin the checked-in Rulesync bundle digest')
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main().catch(error => {
        process.stderr.write(`[RULESYNC_BUNDLE_INVALID] ${error instanceof Error ? error.message : String(error)}\n`)
        process.exitCode = 1
    })
}
