it('captures bounded generated bytes without widening ordinary JSON input', () => {
    const bytes = 'x'.repeat(16_777_216)
    expect(snapshotJson(bytes)).toBeUndefined()
    expect(snapshotGeneratedJson(bytes)).toBe(bytes)
    expect(snapshotGeneratedJson(`${bytes}x`)).toBeUndefined()
    const exact = [bytes, bytes.slice(0, -7)]
    const captured = snapshotGeneratedJson(exact)
    expect(captured).toEqual(exact)
    expect(Object.isFrozen(captured)).toBe(true)
    expect(snapshotGeneratedJson([bytes, bytes.slice(0, -6)])).toBeUndefined()
})

it('refuses hostile generated JSON without invoking accessors or proxies', () => {
    let reads = 0
    const accessor = Object.defineProperty({}, 'bytes', {
        enumerable: true, get() { reads += 1; return 'bytes' },
    })
    expect(snapshotGeneratedJson(accessor)).toBeUndefined()
    expect(snapshotGeneratedJson(new Proxy({ bytes: 'bytes' }, {}))).toBeUndefined()
    expect(snapshotGeneratedJson(Array(1))).toBeUndefined()
    expect(reads).toBe(0)
})

