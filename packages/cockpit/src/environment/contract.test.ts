it('snapshots exact ordered filesystem identity without retaining caller-owned data', () => {
    const identity = {
        dev: 11,
        ino: 22,
        birthtimeNs: '1700000000123456789',
        ancestors: [
            { path: '/tmp/owned-root', dev: 1, ino: 2, birthtimeNs: '0' },
            { path: '/tmp/owned-root/generated', dev: 3, ino: 4, birthtimeNs: '1700000000000000001' },
        ],
    }
    const step = { ...execution, filesystemChecks: [{
        path: '/tmp/owned-root/generated/session', expected: 'directory', identity,
    }] }

    const snapshot = snapshotExecutionStep(step)

    expect(snapshot?.filesystemChecks[0]).toEqual(step.filesystemChecks[0])
    expect(Object.isFrozen(snapshot?.filesystemChecks[0]?.identity)).toBe(true)
    expect(Object.isFrozen(snapshot?.filesystemChecks[0]?.identity?.ancestors)).toBe(true)
    identity.ancestors[1]!.ino = 99
    expect(snapshot?.filesystemChecks[0]?.identity?.ancestors[1]?.ino).toBe(4)
})

