it('supports 4,096 services plus fixed leaves while preserving the public JSON collection bound', () => {
    const services = Array.from({ length: 4_096 }, (_, index) => ({ id: `service-${index}`, kind: 'service', service: `service-${index}` }))
    const completedServices = services.map(({ service }) => ({ service, containerId: 'c'.repeat(64) }))
    const steps = [{ id: 'preflight', kind: 'preflight' }, ...services, { id: 'publish', kind: 'publish-entrypoints', values: [] }]
    const source = lifecycleSource(steps, {
        completedStepIds: steps.slice(0, -1).map(({ id }) => id), progress: { ...progress(), completedServices },
    })
    expect(snapshotLifecyclePlan(source)?.steps).toHaveLength(4_098)
    expect(snapshotJson(Array.from({ length: 4_097 }, () => null))).toBeUndefined()
    expect(snapshotLifecyclePlan(lifecycleSource([...services, { id: 'over', kind: 'service', service: 'over' }]))).toBeUndefined()
})

it('limits compensation to acquired claim-release provenance', () => {
    const ownership = {
        stackId: `stack:${'1'.repeat(64)}`,
        holderId: `holder:${'2'.repeat(64)}:session`,
        recordRevision: 1,
        change: 'acquired',
    } as const
    expect(snapshotLifecyclePlan(lifecycleSource(
        [{ id: 'claim', kind: 'claim', action: 'acquire' }],
        { compensation: [{ step: { id: 'release', kind: 'claim', action: 'release' }, ownership }] },
    ))).toBeDefined()
    expect(snapshotLifecyclePlan(lifecycleSource(
        [{ id: 'claim', kind: 'claim', action: 'acquire' }],
        { compensation: [{ step: { id: 'undo-preflight', kind: 'preflight' }, ownership }] },
    ))).toBeUndefined()
    expect(snapshotLifecyclePlan(lifecycleSource(
        [{ id: 'claim', kind: 'claim', action: 'acquire' }],
        { compensation: [{ step: { id: 'release', kind: 'claim' }, ownership }] },
    ))).toBeUndefined()
    for (const invalidOwnership of [
        { ...ownership, stackId: [`stack:${'1'.repeat(64)}`] },
        { ...ownership, stackId: Object.create(null) },
        { ...ownership, holderId: [`holder:${'2'.repeat(64)}:session`] },
        { ...ownership, holderId: Object.create(null) },
    ]) {
        const candidate = lifecycleSource([{ id: 'claim', kind: 'claim', action: 'acquire' }], {
            compensation: [{ step: { id: 'release', kind: 'claim', action: 'release' }, ownership: invalidOwnership }],
        })
        expect(() => snapshotLifecyclePlan(candidate)).not.toThrow()
        expect(snapshotLifecyclePlan(candidate)).toBeUndefined()
    }
})

