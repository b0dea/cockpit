const lifecycleSource = (
    steps: readonly Record<string, unknown>[],
    options: {
        readonly completedStepIds?: readonly string[]
        readonly compensation?: readonly unknown[]
        readonly diagnostics?: readonly unknown[]
        readonly progress?: Record<string, unknown>
        readonly verb?: string
    } = {},
) => ({
    verb: options.verb ?? 'up',
    progress: options.progress ?? progress(),
    steps,
    resumeBoundary: {
        completedStepIds: options.completedStepIds ?? [],
        nextStepId: steps[options.completedStepIds?.length ?? 0]?.id ?? null,
    },
    compensation: options.compensation ?? [],
    diagnostics: options.diagnostics ?? [],
})

it('snapshots a bounded immutable lifecycle plan as leaf data', () => {
    const source = lifecycleSource([{ id: 'preflight', kind: 'preflight' }])
    const snapshot = snapshotLifecyclePlan(source)
    expect(snapshot).toEqual(source)
    expect(Object.isFrozen(snapshot)).toBe(true)
    expect(Object.isFrozen(snapshot?.steps)).toBe(true)
    expect(Object.isFrozen(snapshot?.progress)).toBe(true)
    expect(Object.isFrozen(snapshot?.progress.completedServices)).toBe(true)
    expect(snapshotLifecyclePlan({ ...source, verb: 'restart' })).toBeUndefined()
    expect(snapshotLifecyclePlan({ ...source, extra: true })).toBeUndefined()
    expect(snapshotLifecyclePlan({ ...source, steps: [{ id: 'x'.repeat(513), kind: 'preflight' }] })).toBeUndefined()
    const oversizedUtf8Id = 'é'.repeat(257)
    expect(snapshotLifecyclePlan({ ...source, steps: [{ id: oversizedUtf8Id, kind: 'preflight' }], resumeBoundary: { completedStepIds: [], nextStepId: oversizedUtf8Id } })).toBeUndefined()
    expect(snapshotLifecyclePlan({ ...source, resumeBoundary: { completedStepIds: ['missing'], nextStepId: null } })).toBeUndefined()
    expect(snapshotLifecyclePlan({ ...source, resumeBoundary: { completedStepIds: [], nextStepId: 'missing' } })).toBeUndefined()
    expect(snapshotLifecyclePlan({ ...source, diagnostics: [{ severity: 'error', code: 'NOT_A_CODE', message: 'bad' }] })).toBeUndefined()
})

it('refuses proxy, accessor, sparse, symbol, and non-enumerable lifecycle input without reading it', () => {
    const source = lifecycleSource([{ id: 'preflight', kind: 'preflight' }])
    expect(snapshotLifecyclePlan(new Proxy(source, {}))).toBeUndefined()
    const { proxy, revoke } = Proxy.revocable(source, {})
    revoke()
    expect(snapshotLifecyclePlan(proxy)).toBeUndefined()
    let reads = 0
    const accessor = { ...source } as Record<string, unknown>
    Object.defineProperty(accessor, 'steps', { enumerable: true, get: () => { reads += 1; return source.steps } })
    expect(snapshotLifecyclePlan(accessor)).toBeUndefined()
    expect(reads).toBe(0)
    expect(snapshotLifecyclePlan({ ...source, steps: Array(1) })).toBeUndefined()
    expect(snapshotLifecyclePlan({ ...source, [Symbol('hidden')]: true })).toBeUndefined()
    const nonEnumerable = { ...source }
    Object.defineProperty(nonEnumerable, 'hidden', { value: true })
    expect(snapshotLifecyclePlan(nonEnumerable)).toBeUndefined()

    expect(snapshotJson(new Proxy({ value: true }, {}))).toBeUndefined()
    const jsonAccessor = {} as Record<string, unknown>
    Object.defineProperty(jsonAccessor, 'value', { enumerable: true, get: () => { reads += 1; return true } })
    expect(snapshotJson(jsonAccessor)).toBeUndefined()
    expect(reads).toBe(0)
})

it('requires semantic lifecycle payloads and rejects legacy runtime steps', () => {
    expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'prepare', kind: 'prepare' }]))).toBeUndefined()
    expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'prepare', kind: 'prepare', execution }]))).toBeDefined()
    expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'service', kind: 'service' }]))).toBeUndefined()
    expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'service', kind: 'service', service: 'web' }]))).toBeDefined()
    for (const kind of ['start-service', 'check-health', 'stop-runtime', 'remove-resource'])
        expect(snapshotLifecyclePlan(lifecycleSource([{ id: kind, kind, service: 'web', execution }]))).toBeUndefined()
    expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'claim', kind: 'claim' }]))).toBeUndefined()
    expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'claim', kind: 'claim', action: 'acquire' }]))).toBeDefined()
})

it('rejects fields forbidden by a lifecycle step kind', () => {
    expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'preflight', kind: 'preflight', execution }]))).toBeUndefined()
    expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'publish', kind: 'publish-entrypoints' }]))).toBeUndefined()
    expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'claim', kind: 'claim', action: 'acquire', service: 'web' }]))).toBeUndefined()
    expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'prepare', kind: 'prepare', action: 'acquire', execution }]))).toBeUndefined()
    expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'service', kind: 'service', service: 'web', execution }]))).toBeUndefined()
})

it('snapshots exact resolved entrypoints with the shared closed kind vocabulary', () => {
    const values = ['entrypoint', 'origin', 'callback_url', 'advertised_listener', 'cors_origin', 'public_base_url']
        .map((kind, index) => ({ name: `route-${index}`, kind, port: `PORT_${index}`, value: `http://127.0.0.1:${4000 + index}` }))
    const snapshot = snapshotLifecyclePlan(lifecycleSource([{ id: 'publish', kind: 'publish-entrypoints', values }]))
    expect(snapshot?.steps[0]).toEqual({ id: 'publish', kind: 'publish-entrypoints', values })
    expect(Object.isFrozen((snapshot?.steps[0] as { values?: unknown[] })?.values)).toBe(true)
    expect(Object.isFrozen((snapshot?.steps[0] as { readonly values: readonly unknown[] }).values[0])).toBe(true)
    for (const value of [
        { ...values[0], name: 'Bad_name' }, { ...values[0], kind: 'legacy-url' }, { ...values[0], port: 'port_1' },
        { ...values[0], value: '' }, { ...values[0], value: 'bad\0value' }, { ...values[0], value: 'é'.repeat(2_049) },
        { ...values[0], extra: true },
    ]) expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'publish', kind: 'publish-entrypoints', values: [value] }]))).toBeUndefined()
    expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'publish', kind: 'publish-entrypoints', values: [values[0], values[0]] }]))).toBeUndefined()
    expect(snapshotLifecyclePlan(lifecycleSource([
        { id: 'publish-one', kind: 'publish-entrypoints', values: [values[0]] },
        { id: 'publish-two', kind: 'publish-entrypoints', values: [values[0]] },
    ]))).toBeUndefined()
    const tooMany = Array.from({ length: 4_097 }, (_, index) => ({ name: `route-${index}`, kind: 'entrypoint', port: 'PORT', value: 'value' }))
    expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'publish', kind: 'publish-entrypoints', values: tooMany }]))).toBeUndefined()
    const oversizedPlan = tooMany.slice(0, 4_096).map((entrypoint) => ({ ...entrypoint, value: 'x'.repeat(256) }))
    expect(snapshotLifecyclePlan(lifecycleSource([{ id: 'publish', kind: 'publish-entrypoints', values: oversizedPlan }]))).toBeUndefined()
})

it('rejects coercible and non-coercible entrypoint fields without throwing', () => {
    const entrypoint = { name: 'route', kind: 'entrypoint', port: 'PORT', value: 'value' }
    for (const invalid of [
        { ...entrypoint, name: ['route'] },
        { ...entrypoint, name: Object.create(null) },
        { ...entrypoint, port: ['PORT'] },
        { ...entrypoint, port: Object.create(null) },
    ]) {
        const candidate = lifecycleSource([{ id: 'publish', kind: 'publish-entrypoints', values: [invalid] }])
        expect(() => snapshotLifecyclePlan(candidate)).not.toThrow()
        expect(snapshotLifecyclePlan(candidate)).toBeUndefined()
    }
    const duplicate = lifecycleSource([{
        id: 'publish', kind: 'publish-entrypoints', values: [entrypoint, { ...entrypoint, name: ['route'] }],
    }])
    expect(snapshotLifecyclePlan(duplicate)).toBeUndefined()
})

it('validates durable progress and its exact completed service prefix', () => {
    const completed = { service: 'api', containerId: 'c'.repeat(64) }
    const source = lifecycleSource(
        [{ id: 'preflight', kind: 'preflight' }, { id: 'api', kind: 'service', service: 'api' }, { id: 'publish', kind: 'publish-entrypoints', values: [] }],
        { completedStepIds: ['preflight', 'api'], progress: { ...progress(), completedServices: [completed] } },
    )
    expect(snapshotLifecyclePlan(source)?.progress.completedServices).toEqual([completed])
    expect(Object.isFrozen(snapshotLifecyclePlan(source)?.progress.completedServices[0])).toBe(true)
    for (const invalidProgress of [
        { ...progress(), workBasisSha256: 'A'.repeat(64) }, { ...progress(), operationGeneration: 'short' },
        { ...progress(), completedServices: [{ ...completed, service: 'Bad_service' }] },
        { ...progress(), completedServices: [{ ...completed, containerId: 'C'.repeat(64) }] },
        { ...progress(), completedServices: [{ ...completed, extra: true }] },
        { ...progress(), completedServices: [completed, completed] }, { ...progress(), extra: true },
    ]) expect(snapshotLifecyclePlan({ ...source, progress: invalidProgress })).toBeUndefined()
    expect(snapshotLifecyclePlan({ ...source, progress: progress() })).toBeUndefined()
    expect(snapshotLifecyclePlan({ ...source, progress: { ...progress(), completedServices: [{ ...completed, service: 'other' }] } })).toBeUndefined()
    const tooMany = Array.from({ length: 4_097 }, (_, index) => ({ service: `service-${index}`, containerId: 'c'.repeat(64) }))
    expect(snapshotLifecyclePlan({ ...source, progress: { ...progress(), completedServices: tooMany } })).toBeUndefined()
})

